import React, { useEffect, useRef, useState } from 'react';
import * as THREE from 'three';
import { 
  Play, 
  Pause, 
  RotateCcw, 
  Info, 
  Layers, 
  Cpu, 
  Zap, 
  AlertTriangle, 
  CheckCircle2, 
  Maximize2,
  HelpCircle,
  ArrowRight
} from 'lucide-react';
import { FaultCondition } from '../../types';

interface Model3DPageProps {
  currentCondition: FaultCondition;
  onSetCondition: (condition: FaultCondition) => void;
}

interface ComponentInfo {
  id: string;
  name: string;
  step: number;
  category: string;
  description: string;
  physicsRole: string;
}

const SYSTEM_COMPONENTS: ComponentInfo[] = [
  {
    id: 'input',
    name: '1. Data Input Source',
    step: 1,
    category: 'Electronic Subsystem',
    description: 'Digital binary data stream generated by telecom multiplexer, video server, or smart city sensor hub.',
    physicsRole: 'Provides electronic TTL/LVDS electrical pulse sequences (0s and 1s) representing raw packets.'
  },
  {
    id: 'transmitter',
    name: '2. Optical Transmitter (Laser/LED)',
    step: 2,
    category: 'Electro-Optic Conversion',
    description: 'Distributed Feedback (DFB) Semiconductor Laser Diode modulating light at 1550 nm infrared wavelength.',
    physicsRole: 'Converts electrical voltage variations into coherent optical photon pulses launched into the core.'
  },
  {
    id: 'fibre',
    name: '3. Optical Fibre Cable (Waveguide)',
    step: 3,
    category: 'Photonic Transmission',
    description: 'Single-mode silica glass fibre with 9µm core (refractive index n₁=1.468) and 125µm cladding (n₂=1.462).',
    physicsRole: 'Transmits photons over tens of kilometres via Total Internal Reflection with attenuation <0.2 dB/km.'
  },
  {
    id: 'receiver',
    name: '4. Receiver / Photodetector',
    step: 4,
    category: 'Opto-Electric Conversion',
    description: 'High-speed InGaAs PIN / APD Photodiode with integrated transimpedance amplifier (TIA).',
    physicsRole: 'Absorbs incident photons via photoelectric bandgap excitation to produce proportional photocurrent.'
  },
  {
    id: 'daq',
    name: '5. Data Acquisition Unit (DAQ)',
    step: 5,
    category: 'Signal Conditioning',
    description: 'High-speed 16-bit analog-to-digital converter (ADC) sampling optical power and voltage fluctuations.',
    physicsRole: 'Digitizes continuous analog photocurrent into discrete time-series arrays for computational analysis.'
  },
  {
    id: 'aiml',
    name: '6. AI/ML Processing Unit',
    step: 6,
    category: 'Edge Neural Computing',
    description: 'Embedded Linux micro-workstation executing machine learning classification algorithms (Random Forest / 1D-CNN).',
    physicsRole: 'Calculates statistical features (mean, variance, gradient, kurtosis) and matches signature vectors against trained fault profiles.'
  },
  {
    id: 'alert',
    name: '7. Fault Alert & Telemetry Display',
    step: 7,
    category: 'Network Operations UI',
    description: 'Real-time monitoring console displaying network health, suspected fault localization, and automated dispatch alerts.',
    physicsRole: 'Notifies NOC operators within milliseconds of abnormal attenuation, macrobends, or physical fibre severance.'
  }
];

export const Model3DPage: React.FC<Model3DPageProps> = ({
  currentCondition,
  onSetCondition
}) => {
  const mountRef = useRef<HTMLDivElement | null>(null);
  const [isPlaying, setIsPlaying] = useState<boolean>(true);
  const [selectedComp, setSelectedComp] = useState<ComponentInfo>(SYSTEM_COMPONENTS[2]); // Fibre by default
  const [isFaultMode, setIsFaultMode] = useState<boolean>(currentCondition !== 'normal');

  // Sync external condition
  useEffect(() => {
    setIsFaultMode(currentCondition !== 'normal');
  }, [currentCondition]);

  const toggleFault = () => {
    const nextFault = !isFaultMode;
    setIsFaultMode(nextFault);
    onSetCondition(nextFault ? 'bending' : 'normal');
  };

  useEffect(() => {
    const container = mountRef.current;
    if (!container) return;

    // Three.js Scene Setup
    const scene = new THREE.Scene();
    scene.background = new THREE.Color(0x060e1b);

    const width = container.clientWidth || 800;
    const height = container.clientHeight || 500;

    const camera = new THREE.PerspectiveCamera(45, width / height, 0.1, 1000);
    camera.position.set(0, 5, 22);

    const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true });
    renderer.setSize(width, height);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
    renderer.shadowMap.enabled = true;
    container.innerHTML = '';
    container.appendChild(renderer.domElement);

    // Lighting
    const ambientLight = new THREE.AmbientLight(0xffffff, 0.8);
    scene.add(ambientLight);

    const dirLight = new THREE.DirectionalLight(0x38bdf8, 1.2);
    dirLight.position.set(10, 20, 15);
    scene.add(dirLight);

    const cyanPointLight = new THREE.PointLight(0x06b6d4, 2, 30);
    cyanPointLight.position.set(-6, 0, 0);
    scene.add(cyanPointLight);

    // Group for entire system
    const systemGroup = new THREE.Group();
    scene.add(systemGroup);

    // 1. Data Input Block (Leftmost)
    const inputGeo = new THREE.BoxGeometry(2, 1.4, 1.6);
    const inputMat = new THREE.MeshStandardMaterial({ 
      color: 0x1e293b, 
      roughness: 0.3,
      metalness: 0.8
    });
    const inputMesh = new THREE.Mesh(inputGeo, inputMat);
    inputMesh.position.set(-11, 0, 0);
    systemGroup.add(inputMesh);

    // 2. Optical Transmitter Module
    const txGeo = new THREE.BoxGeometry(2.4, 2, 2);
    const txMat = new THREE.MeshStandardMaterial({ 
      color: 0x0f172a, 
      roughness: 0.2, 
      metalness: 0.9,
      emissive: 0x0369a1,
      emissiveIntensity: 0.3
    });
    const txMesh = new THREE.Mesh(txGeo, txMat);
    txMesh.position.set(-8, 0, 0);
    systemGroup.add(txMesh);

    // Laser symbol on transmitter
    const laserEmittingRing = new THREE.Mesh(
      new THREE.CylinderGeometry(0.3, 0.3, 0.4, 16),
      new THREE.MeshBasicMaterial({ color: 0x38bdf8 })
    );
    laserEmittingRing.rotation.z = Math.PI / 2;
    laserEmittingRing.position.set(-6.7, 0, 0);
    systemGroup.add(laserEmittingRing);

    // 3. Optical Fibre Cable
    // Cladding (Transparent outer cylinder)
    const claddingGeo = new THREE.CylinderGeometry(0.7, 0.7, 10, 32);
    const claddingMat = new THREE.MeshPhysicalMaterial({
      color: 0x0284c7,
      transparent: true,
      opacity: 0.25,
      roughness: 0.1,
      transmission: 0.8,
      thickness: 0.5
    });
    const claddingMesh = new THREE.Mesh(claddingGeo, claddingMat);
    claddingMesh.rotation.z = Math.PI / 2;
    claddingMesh.position.set(-1.5, 0, 0);
    systemGroup.add(claddingMesh);

    // Glowing Core (Inner thin cylinder)
    const coreGeo = new THREE.CylinderGeometry(0.2, 0.2, 10, 32);
    const coreMat = new THREE.MeshStandardMaterial({
      color: 0x06b6d4,
      emissive: 0x06b6d4,
      emissiveIntensity: 1.5,
      roughness: 0.1
    });
    const coreMesh = new THREE.Mesh(coreGeo, coreMat);
    coreMesh.rotation.z = Math.PI / 2;
    coreMesh.position.set(-1.5, 0, 0);
    systemGroup.add(coreMesh);

    // Animated Photon Pulses (Spheres flowing through the core)
    const photonCount = 12;
    const photons: THREE.Mesh[] = [];
    const photonGeo = new THREE.SphereGeometry(0.22, 16, 16);
    const photonMat = new THREE.MeshBasicMaterial({ color: 0xe0f2fe });

    for (let i = 0; i < photonCount; i++) {
      const p = new THREE.Mesh(photonGeo, photonMat);
      p.position.set(-6.5 + (i * (10 / photonCount)), 0, 0);
      systemGroup.add(p);
      photons.push(p);
    }

    // Leaking Photons (Visualizing bending/cut loss)
    const leakPhotons: THREE.Mesh[] = [];
    const leakGeo = new THREE.SphereGeometry(0.15, 12, 12);
    const leakMat = new THREE.MeshBasicMaterial({ color: 0xf43f5e });
    for (let i = 0; i < 6; i++) {
      const lp = new THREE.Mesh(leakGeo, leakMat);
      lp.visible = isFaultMode;
      lp.position.set(-1.5, 0.5, 0);
      systemGroup.add(lp);
      leakPhotons.push(lp);
    }

    // 4. Optical Receiver (Photodetector)
    const rxGeo = new THREE.BoxGeometry(2.4, 2, 2);
    const rxMat = new THREE.MeshStandardMaterial({ 
      color: 0x0f172a, 
      roughness: 0.2, 
      metalness: 0.9,
      emissive: 0x0284c7,
      emissiveIntensity: 0.2
    });
    const rxMesh = new THREE.Mesh(rxGeo, rxMat);
    rxMesh.position.set(4.5, 0, 0);
    systemGroup.add(rxMesh);

    // Photodetector sensor ring
    const detectorRing = new THREE.Mesh(
      new THREE.CylinderGeometry(0.3, 0.3, 0.3, 16),
      new THREE.MeshBasicMaterial({ color: 0x38bdf8 })
    );
    detectorRing.rotation.z = Math.PI / 2;
    detectorRing.position.set(3.3, 0, 0);
    systemGroup.add(detectorRing);

    // 5. Data Acquisition Unit (DAQ)
    const daqGeo = new THREE.BoxGeometry(1.8, 1.4, 1.6);
    const daqMat = new THREE.MeshStandardMaterial({ 
      color: 0x1e1b4b, 
      roughness: 0.4, 
      metalness: 0.7 
    });
    const daqMesh = new THREE.Mesh(daqGeo, daqMat);
    daqMesh.position.set(7.5, 0, 0);
    systemGroup.add(daqMesh);

    // 6. AI/ML Processing Unit (Central Compute)
    const aiGeo = new THREE.BoxGeometry(2.2, 2.2, 1.8);
    const aiMat = new THREE.MeshStandardMaterial({ 
      color: 0x2e1065, 
      roughness: 0.2, 
      metalness: 0.8,
      emissive: 0x7c3aed,
      emissiveIntensity: 0.4
    });
    const aiMesh = new THREE.Mesh(aiGeo, aiMat);
    aiMesh.position.set(10.5, 0, 0);
    systemGroup.add(aiMesh);

    // 7. Alert & Display Console
    const monitorGeo = new THREE.BoxGeometry(2.5, 1.8, 0.3);
    const monitorMat = new THREE.MeshStandardMaterial({ 
      color: 0x020617,
      emissive: isFaultMode ? 0x991b1b : 0x065f46,
      emissiveIntensity: 0.7
    });
    const monitorMesh = new THREE.Mesh(monitorGeo, monitorMat);
    monitorMesh.position.set(13.8, 0.5, 0);
    systemGroup.add(monitorMesh);

    const standMesh = new THREE.Mesh(
      new THREE.CylinderGeometry(0.1, 0.1, 1.2, 16),
      new THREE.MeshStandardMaterial({ color: 0x334155 })
    );
    standMesh.position.set(13.8, -0.6, 0);
    systemGroup.add(standMesh);

    // Connecting wires / PCB buses
    const createWire = (fromX: number, toX: number, y: number, color = 0x38bdf8) => {
      const geo = new THREE.CylinderGeometry(0.04, 0.04, Math.abs(toX - fromX), 8);
      const mat = new THREE.MeshBasicMaterial({ color });
      const wire = new THREE.Mesh(geo, mat);
      wire.rotation.z = Math.PI / 2;
      wire.position.set((fromX + toX) / 2, y, 0);
      systemGroup.add(wire);
    };

    createWire(-10, -9.2, 0, 0x94a3b8);
    createWire(5.7, 6.6, 0, 0x94a3b8);
    createWire(8.4, 9.4, 0, 0xa855f7);
    createWire(11.6, 12.5, 0, 0xa855f7);

    // Ground Grid
    const grid = new THREE.GridHelper(36, 36, 0x0e7490, 0x1e293b);
    grid.position.y = -2;
    scene.add(grid);

    // Mouse Interaction (Orbit / Drag Rotation)
    let isDragging = false;
    let prevMouseX = 0;
    let prevMouseY = 0;

    const onMouseDown = (e: MouseEvent) => {
      isDragging = true;
      prevMouseX = e.clientX;
      prevMouseY = e.clientY;
    };

    const onMouseMove = (e: MouseEvent) => {
      if (!isDragging) return;
      const deltaX = e.clientX - prevMouseX;
      const deltaY = e.clientY - prevMouseY;
      systemGroup.rotation.y += deltaX * 0.008;
      systemGroup.rotation.x += deltaY * 0.005;
      systemGroup.rotation.x = Math.max(-0.6, Math.min(0.6, systemGroup.rotation.x));
      prevMouseX = e.clientX;
      prevMouseY = e.clientY;
    };

    const onMouseUp = () => {
      isDragging = false;
    };

    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      camera.position.z += e.deltaY * 0.015;
      camera.position.z = Math.max(12, Math.min(35, camera.position.z));
    };

    const dom = renderer.domElement;
    dom.addEventListener('mousedown', onMouseDown);
    window.addEventListener('mousemove', onMouseMove);
    window.addEventListener('mouseup', onMouseUp);
    dom.addEventListener('wheel', onWheel, { passive: false });

    // Animation Loop
    let animationId: number;
    const speed = isFaultMode ? 0.04 : 0.08;

    const animate = () => {
      if (isPlaying) {
        // Move photons along the core
        photons.forEach((p) => {
          p.position.x += speed;
          if (p.position.x > 3.4) {
            p.position.x = -6.5;
          }
        });

        // Leaking photons animation if in fault mode
        if (isFaultMode) {
          leakPhotons.forEach((lp, idx) => {
            lp.visible = true;
            lp.position.y += 0.02 + idx * 0.005;
            lp.position.z += (Math.sin(Date.now() * 0.005 + idx) * 0.02);
            if (lp.position.y > 1.8) {
              lp.position.y = 0.4;
              lp.position.z = 0;
            }
          });
        } else {
          leakPhotons.forEach((lp) => {
            lp.visible = false;
          });
        }

        // Pulse the AI core light
        aiMat.emissiveIntensity = 0.4 + Math.sin(Date.now() * 0.005) * 0.2;
      }

      renderer.render(scene, camera);
      animationId = requestAnimationFrame(animate);
    };

    animate();

    // Resize handler
    const handleResize = () => {
      if (!container) return;
      const w = container.clientWidth;
      const h = container.clientHeight;
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
      renderer.setSize(w, h);
    };
    window.addEventListener('resize', handleResize);

    return () => {
      cancelAnimationFrame(animationId);
      dom.removeEventListener('mousedown', onMouseDown);
      window.removeEventListener('mousemove', onMouseMove);
      window.removeEventListener('mouseup', onMouseUp);
      dom.removeEventListener('wheel', onWheel);
      window.removeEventListener('resize', handleResize);
      renderer.dispose();
      if (container.contains(renderer.domElement)) {
        container.removeChild(renderer.domElement);
      }
    };
  }, [isPlaying, isFaultMode]);

  return (
    <div className="space-y-6 pb-12">
      {/* 3D Viewport Card */}
      <div className="rounded-2xl bg-[#081224] border border-slate-800 overflow-hidden shadow-2xl">
        {/* Top Control Bar */}
        <div className="p-4 border-b border-slate-800 flex flex-wrap items-center justify-between gap-3 bg-[#060e1b]">
          <div className="flex items-center gap-3">
            <span className="text-sm font-bold text-white flex items-center gap-2">
              <Zap className="w-4 h-4 text-cyan-400" />
              Interactive Photonic System 3D Simulation
            </span>
            <span className="text-xs text-slate-400 hidden sm:inline">
              (Drag to rotate, scroll to zoom)
            </span>
          </div>

          <div className="flex items-center gap-2">
            {/* Play/Pause */}
            <button
              onClick={() => setIsPlaying(!isPlaying)}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-xs font-semibold text-white border border-slate-700 transition-all active:scale-95"
            >
              {isPlaying ? <Pause className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
              <span>{isPlaying ? 'Pause' : 'Play'}</span>
            </button>

            {/* Normal / Fault Switch */}
            <button
              onClick={toggleFault}
              className={`flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg text-xs font-bold border transition-all active:scale-95 ${
                isFaultMode
                  ? 'bg-rose-950/80 text-rose-300 border-rose-500/60 shadow-sm shadow-rose-950'
                  : 'bg-emerald-950/80 text-emerald-300 border-emerald-500/60 shadow-sm shadow-emerald-950'
              }`}
            >
              {isFaultMode ? (
                <>
                  <AlertTriangle className="w-3.5 h-3.5 text-rose-400" />
                  <span>Fault Condition Active</span>
                </>
              ) : (
                <>
                  <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                  <span>Normal Signal Propagation</span>
                </>
              )}
            </button>
          </div>
        </div>

        {/* 3D WebGL Canvas Viewport */}
        <div className="relative w-full h-[440px] sm:h-[480px] bg-[#060e1b]" ref={mountRef}>
          {/* Floating HUD Badges inside canvas */}
          <div className="absolute top-4 left-4 bg-slate-950/80 backdrop-blur-md px-3 py-2 rounded-xl border border-slate-800 text-xs space-y-1 pointer-events-none">
            <div className="flex items-center gap-2 text-cyan-400 font-semibold">
              <span className="w-2 h-2 rounded-full bg-cyan-400" />
              <span>Single-Mode Optical Waveguide Core</span>
            </div>
            <p className="text-[11px] text-slate-400 font-mono">
              Core: 9µm (n₁=1.468) | Cladding: 125µm (n₂=1.462)
            </p>
          </div>

          <div className="absolute top-4 right-4 bg-slate-950/80 backdrop-blur-md px-3 py-2 rounded-xl border border-slate-800 text-xs text-right space-y-1 pointer-events-none">
            <span className="text-slate-400 block text-[10px] uppercase tracking-wider font-semibold">Channel Telemetry</span>
            <div className="font-mono text-cyan-300 font-bold">
              {isFaultMode ? '-21.8 dBm (Bending)' : '-12.4 dBm (Nominal)'}
            </div>
          </div>
        </div>

        {/* Component Selector strip below 3D canvas */}
        <div className="p-3 bg-[#071020] border-t border-slate-800 overflow-x-auto">
          <div className="flex items-center gap-2 min-w-max">
            {SYSTEM_COMPONENTS.map((comp) => (
              <button
                key={comp.id}
                onClick={() => setSelectedComp(comp)}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold whitespace-nowrap transition-all ${
                  selectedComp.id === comp.id
                    ? 'bg-cyan-500/20 text-cyan-300 border border-cyan-500/50'
                    : 'text-slate-400 hover:text-white bg-slate-900/60 border border-slate-800'
                }`}
              >
                {comp.name}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Selected Component Detailed Inspector Card */}
      <div className="rounded-xl bg-[#081224] border border-cyan-800/40 p-5 space-y-3">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-800 pb-3">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-cyan-950/80 border border-cyan-800/50 flex items-center justify-center text-cyan-400 font-bold font-mono text-sm">
              {selectedComp.step}
            </div>
            <div>
              <h3 className="text-sm font-bold text-white">{selectedComp.name}</h3>
              <span className="text-[11px] text-cyan-400">{selectedComp.category}</span>
            </div>
          </div>
          <span className="text-xs text-slate-400 font-mono">Stage {selectedComp.step} of 7</span>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs">
          <div className="space-y-1">
            <span className="text-slate-400 font-semibold block text-[11px]">System Purpose &amp; Operation</span>
            <p className="text-slate-300 leading-relaxed">{selectedComp.description}</p>
          </div>
          <div className="space-y-1">
            <span className="text-slate-400 font-semibold block text-[11px]">Physics &amp; Signal Role</span>
            <p className="text-slate-300 leading-relaxed">{selectedComp.physicsRole}</p>
          </div>
        </div>
      </div>

      {/* End-to-End Data Flow Diagram */}
      <div className="rounded-xl bg-[#081224] border border-slate-800 p-5 space-y-4">
        <div>
          <h3 className="text-sm font-bold text-white">End-to-End Data Flow Architecture</h3>
          <p className="text-xs text-slate-400">Sequential computational and photonic pipeline</p>
        </div>

        <div className="grid grid-cols-2 sm:grid-cols-4 lg:grid-cols-7 gap-2">
          {SYSTEM_COMPONENTS.map((comp, idx) => (
            <div
              key={comp.id}
              onClick={() => setSelectedComp(comp)}
              className={`p-3 rounded-lg border text-left cursor-pointer transition-all ${
                selectedComp.id === comp.id
                  ? 'bg-cyan-950/70 border-cyan-500/60 text-white'
                  : 'bg-slate-900/60 border-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              <div className="text-[10px] font-mono text-cyan-400 mb-1">Step 0{idx + 1}</div>
              <div className="text-xs font-bold truncate">{comp.name.split('. ')[1]}</div>
              <div className="text-[10px] text-slate-400 mt-1 truncate">{comp.category}</div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};
